import 'reflect-metadata';

import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

import { NestFactory } from '@nestjs/core';

import { AppModule } from '../apps/api/dist/app.module.js';
import { createDebtShiftOpenApiDocument } from '../apps/api/dist/openapi.js';

const specificationPath = resolve('docs/openapi.json');
const generatedTypesPath = resolve('packages/sdk/src/generated/api.ts');
const app = await NestFactory.create(AppModule, { logger: false });

try {
  app.setGlobalPrefix('v1');
  const document = stableObject(createDebtShiftOpenApiDocument(app));
  await mkdir(dirname(specificationPath), { recursive: true });
  await mkdir(dirname(generatedTypesPath), { recursive: true });
  await writeFile(specificationPath, `${JSON.stringify(document, null, 2)}\n`, 'utf8');
  await writeFile(generatedTypesPath, emitTypeScript(document), 'utf8');
  process.stdout.write(
    `Generated ${relative(specificationPath)} and ${relative(generatedTypesPath)}\n`,
  );
} finally {
  await app.close();
}

function emitTypeScript(document) {
  const operations = [];
  const methods = ['get', 'post', 'put', 'patch', 'delete', 'options', 'head'];
  for (const [path, pathItem] of Object.entries(document.paths ?? {})) {
    for (const method of methods) {
      const operation = pathItem?.[method];
      if (!operation) continue;
      const operationId = operation.operationId;
      if (typeof operationId !== 'string' || operationId.length === 0) {
        throw new Error(`OpenAPI operation ${method.toUpperCase()} ${path} has no operationId.`);
      }
      operations.push({ method: method.toUpperCase(), operation, operationId, path });
    }
  }
  operations.sort((left, right) => left.operationId.localeCompare(right.operationId));

  const lines = [
    '/* This file is generated by scripts/generate-openapi.mjs. Do not edit manually. */',
    '',
    'export interface DebtShiftApiOperations {',
  ];
  for (const entry of operations) {
    lines.push(`  ${JSON.stringify(entry.operationId)}: {`);
    lines.push(`    method: ${JSON.stringify(entry.method)};`);
    lines.push(`    path: ${JSON.stringify(entry.path)};`);
    lines.push(
      `    parameters: ${parametersType(entry.operation.parameters, document, entry.operation)};`,
    );
    lines.push(
      `    requestBody: ${requestBodyType(entry.operation.requestBody, document, entry.operation)};`,
    );
    lines.push(
      `    responses: ${responsesType(entry.operation.responses, document, entry.operation)};`,
    );
    lines.push('  };');
  }
  lines.push('}', '');
  lines.push('export type DebtShiftOperationId = keyof DebtShiftApiOperations;');
  lines.push(
    'export type DebtShiftOperation<TId extends DebtShiftOperationId> = DebtShiftApiOperations[TId];',
  );
  lines.push(
    'export type DebtShiftRequestBody<TId extends DebtShiftOperationId> = DebtShiftOperation<TId>["requestBody"];',
  );
  lines.push(
    'export type DebtShiftParameters<TId extends DebtShiftOperationId> = DebtShiftOperation<TId>["parameters"];',
  );
  lines.push(
    'export type DebtShiftResponses<TId extends DebtShiftOperationId> = DebtShiftOperation<TId>["responses"];',
  );
  lines.push(
    'export type DebtShiftSuccessResponse<TId extends DebtShiftOperationId> = DebtShiftResponses<TId>[Extract<keyof DebtShiftResponses<TId>, 200 | 201 | 202 | 204>];',
  );
  lines.push('');
  return `${lines.join('\n')}\n`;
}

function parametersType(parameters, document, rootSchema) {
  if (!Array.isArray(parameters) || parameters.length === 0) return 'never';
  const groups = new Map();
  for (const unresolved of parameters) {
    const parameter = resolveReference(unresolved, document, rootSchema);
    if (!parameter || typeof parameter.name !== 'string' || typeof parameter.in !== 'string') {
      continue;
    }
    const values = groups.get(parameter.in) ?? [];
    values.push(parameter);
    groups.set(parameter.in, values);
  }
  if (groups.size === 0) return 'never';
  const fields = [];
  for (const [location, values] of [...groups].sort(([left], [right]) =>
    left.localeCompare(right),
  )) {
    const properties = values
      .sort((left, right) => left.name.localeCompare(right.name))
      .map((parameter) => {
        const optional = parameter.required ? '' : '?';
        return `${JSON.stringify(parameter.name)}${optional}: ${schemaType(parameter.schema, document, rootSchema, new Set())}`;
      });
    fields.push(`${JSON.stringify(location)}: { ${properties.join('; ')} }`);
  }
  return `{ ${fields.join('; ')} }`;
}

function requestBodyType(requestBody, document, rootSchema) {
  if (!requestBody) return 'never';
  const resolved = resolveReference(requestBody, document, rootSchema);
  const schema = preferredContentSchema(resolved?.content);
  return schemaType(schema, document, schema ?? rootSchema, new Set());
}

function responsesType(responses, document, rootSchema) {
  const fields = [];
  for (const [status, unresolved] of Object.entries(responses ?? {}).sort(([left], [right]) =>
    left.localeCompare(right, undefined, { numeric: true }),
  )) {
    const response = resolveReference(unresolved, document, rootSchema);
    const schema = preferredContentSchema(response?.content);
    const responseType = schemaType(schema, document, schema ?? rootSchema, new Set());
    const key = /^[0-9]+$/.test(status) ? status : JSON.stringify(status);
    fields.push(`${key}: ${responseType}`);
  }
  return fields.length === 0 ? 'Record<string, unknown>' : `{ ${fields.join('; ')} }`;
}

function preferredContentSchema(content) {
  if (!content || typeof content !== 'object') return undefined;
  return (
    content['application/json']?.schema ??
    content['text/event-stream']?.schema ??
    content['text/plain']?.schema ??
    Object.values(content)[0]?.schema
  );
}

function schemaType(unresolved, document, rootSchema, seen) {
  if (!unresolved || typeof unresolved !== 'object') return 'unknown';
  if ('$ref' in unresolved) {
    if (seen.has(unresolved.$ref)) return 'unknown';
    const nextSeen = new Set(seen);
    nextSeen.add(unresolved.$ref);
    return schemaType(
      resolveReference(unresolved, document, rootSchema),
      document,
      rootSchema,
      nextSeen,
    );
  }
  if (Object.hasOwn(unresolved, 'const')) return literal(unresolved.const);
  if (Array.isArray(unresolved.enum)) {
    return unresolved.enum.length === 0 ? 'never' : unresolved.enum.map(literal).join(' | ');
  }
  for (const keyword of ['oneOf', 'anyOf']) {
    if (Array.isArray(unresolved[keyword])) {
      return unresolved[keyword]
        .map((schema) => schemaType(schema, document, rootSchema, new Set(seen)))
        .join(' | ');
    }
  }
  if (Array.isArray(unresolved.allOf)) {
    return unresolved.allOf
      .map((schema) => schemaType(schema, document, rootSchema, new Set(seen)))
      .join(' & ');
  }
  if (Array.isArray(unresolved.type)) {
    return unresolved.type
      .map((type) => schemaType({ ...unresolved, type }, document, rootSchema, new Set(seen)))
      .join(' | ');
  }
  if (unresolved.type === 'string') return 'string';
  if (unresolved.type === 'number' || unresolved.type === 'integer') return 'number';
  if (unresolved.type === 'boolean') return 'boolean';
  if (unresolved.type === 'null') return 'null';
  if (unresolved.type === 'array' || unresolved.items) {
    return `Array<${schemaType(unresolved.items, document, rootSchema, new Set(seen))}>`;
  }
  if (unresolved.type === 'object' || unresolved.properties || unresolved.additionalProperties) {
    const required = new Set(unresolved.required ?? []);
    const properties = Object.entries(unresolved.properties ?? {}).map(([name, schema]) => {
      const optional = required.has(name) ? '' : '?';
      return `${JSON.stringify(name)}${optional}: ${schemaType(schema, document, rootSchema, new Set(seen))}`;
    });
    const object = properties.length === 0 ? '{}' : `{ ${properties.join('; ')} }`;
    if (unresolved.additionalProperties === true) return `${object} & Record<string, unknown>`;
    if (unresolved.additionalProperties && typeof unresolved.additionalProperties === 'object') {
      return `${object} & Record<string, ${schemaType(unresolved.additionalProperties, document, rootSchema, new Set(seen))}>`;
    }
    return object;
  }
  return 'unknown';
}

function resolveReference(value, document, rootSchema) {
  if (!value || typeof value !== 'object' || typeof value.$ref !== 'string') return value;
  if (!value.$ref.startsWith('#/')) return undefined;
  const source = value.$ref.startsWith('#/$defs/') ? rootSchema : document;
  return value.$ref
    .slice(2)
    .split('/')
    .map((part) => part.replaceAll('~1', '/').replaceAll('~0', '~'))
    .reduce((current, part) => current?.[part], source);
}

function literal(value) {
  if (value === null) return 'null';
  if (typeof value === 'string' || typeof value === 'number' || typeof value === 'boolean') {
    return JSON.stringify(value);
  }
  return 'unknown';
}

function stableObject(value) {
  if (Array.isArray(value)) return value.map(stableObject);
  if (value === null || typeof value !== 'object') return value;
  return Object.fromEntries(
    Object.entries(value)
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([key, child]) => [key, stableObject(child)]),
  );
}

function relative(path) {
  return path.replace(`${resolve('.')}\\`, '').replaceAll('\\', '/');
}
